//! A loaded dimension (vanilla: `WorldServer`, `ChunkProviderServer`, `AnvilChunkLoader`).

use std::collections::HashMap;
use std::path::{Path, PathBuf};

use krol_nbt::{Compound, List, Tag};
use krol_world::chunk::Chunk;
use krol_world::level::LevelData;
use krol_world::region::{RegionFile, region_file_name};
use tracing::{error, info};

/// Blocks with a tile entity (`ITileEntityProvider`).
fn has_tile_entity(id: u16) -> bool {
    matches!(
        id,
        23 | 25
            | 36
            | 52
            | 54
            | 61
            | 62
            | 63
            | 68
            | 84
            | 116
            | 117
            | 119
            | 130
            | 137
            | 138
            | 140
            | 144
            | 146
            | 149
            | 150
            | 151
            | 154
            | 158
            | 176
            | 177
            | 178
    )
}

/// One dimension's chunk storage.
#[derive(Debug)]
pub struct World {
    /// Block changes per chunk since the last flush, as vanilla's `PlayerInstance`
    /// records them (`x << 12 | z << 8 | y`, at most 64; 64 means "resend sections").
    pub pending_changes: HashMap<(i32, i32), (Vec<u16>, u16)>,
    /// Dimension id (0 overworld, -1 nether, 1 end).
    pub dimension: i8,
    /// Directory holding this dimension's `region/` folder.
    pub dir: PathBuf,
    /// Whether the dimension has sky light.
    pub has_sky: bool,
    chunks: HashMap<(i32, i32), LoadedChunk>,
    regions: HashMap<(i32, i32), RegionFile>,
}

#[derive(Debug)]
struct LoadedChunk {
    chunk: Chunk,
    modified: bool,
    /// Loaded from disk (as opposed to a placeholder for a chunk vanilla would generate).
    from_disk: bool,
    /// Ticked at least once by the world (vanilla: `Chunk.field_150815_m`).
    ticked: bool,
}

impl World {
    /// Opens the dimension stored under `dir`.
    pub fn new(dimension: i8, dir: PathBuf) -> Self {
        Self {
            dimension,
            dir,
            has_sky: dimension == 0,
            chunks: HashMap::new(),
            regions: HashMap::new(),
            pending_changes: HashMap::new(),
        }
    }

    /// Sets a block (vanilla `setBlockState` with update flags 3) and records the change
    /// for the end-of-tick flush to watching players.
    pub fn set_block(&mut self, x: i32, y: i32, z: i32, state: u16) {
        if !(0..256).contains(&y) {
            return;
        }
        // Chunk.setBlockState: setting the same state changes nothing.
        let old = self.block(x, y, z);
        if old == state {
            return;
        }
        let has_sky = self.has_sky;
        self.chunk_mut(x >> 4, z >> 4).set_block(
            (x & 15) as usize,
            y as usize,
            (z & 15) as usize,
            state,
            has_sky,
        );
        self.update_tile_entity((x, y, z), old, state);
        // Vanilla PlayerInstance.flagChunkForUpdate.
        let entry = self.pending_changes.entry((x >> 4, z >> 4)).or_default();
        entry.1 |= 1 << (y >> 4);
        if entry.0.len() < 64 {
            let packed = ((x & 15) as u16) << 12 | ((z & 15) as u16) << 8 | y as u16;
            if !entry.0.contains(&packed) {
                entry.0.push(packed);
            }
        }
    }

    /// The dimension name vanilla prints (`WorldProvider.getDimensionName`).
    pub fn dimension_name(&self) -> &'static str {
        match self.dimension {
            -1 => "Nether",
            1 => "The End",
            _ => "Overworld",
        }
    }

    fn region(&mut self, cx: i32, cz: i32) -> Option<&mut RegionFile> {
        let key = (cx >> 5, cz >> 5);
        if !self.regions.contains_key(&key) {
            let dir = self.dir.join("region");
            std::fs::create_dir_all(&dir).ok()?;
            match RegionFile::open(&dir.join(region_file_name(cx, cz))) {
                Ok(r) => {
                    self.regions.insert(key, r);
                }
                Err(e) => {
                    error!("Couldn't open region file for chunk ({cx}, {cz}): {e}");
                    return None;
                }
            }
        }
        self.regions.get_mut(&key)
    }

    /// Returns the chunk at `(cx, cz)`, loading it from disk if needed.
    ///
    /// TODO(M6): chunks missing from disk are generated by vanilla; krol currently
    /// substitutes an empty (all-air) chunk.
    pub fn chunk(&mut self, cx: i32, cz: i32) -> &Chunk {
        if !self.chunks.contains_key(&(cx, cz)) {
            let has_sky = self.has_sky;
            let loaded = self
                .region(cx, cz)
                .and_then(|r| r.read_chunk(cx & 31, cz & 31).ok().flatten())
                .and_then(|root| match Chunk::from_nbt(&root, cx, cz, has_sky) {
                    Ok(c) => Some(c),
                    Err(e) => {
                        error!("Couldn't load chunk ({cx}, {cz}): {e}");
                        None
                    }
                });
            let from_disk = loaded.is_some();
            let chunk = loaded.unwrap_or_else(|| Chunk::empty(cx, cz));
            self.chunks.insert(
                (cx, cz),
                LoadedChunk {
                    chunk,
                    modified: false,
                    from_disk,
                    ticked: false,
                },
            );
            self.populate_around(cx, cz);
        }
        &self.chunks[&(cx, cz)].chunk
    }

    fn loaded(&self, cx: i32, cz: i32) -> bool {
        self.chunks.contains_key(&(cx, cz))
    }

    /// Marks a chunk terrain-populated (vanilla: `IChunkProvider.populate`).
    ///
    /// TODO(M6): run the generator's population (structures, decorations). The flat
    /// worlds used so far have none, so only the flag changes.
    fn populate(&mut self, cx: i32, cz: i32) {
        if let Some(c) = self.chunks.get_mut(&(cx, cz))
            && c.from_disk
            && !c.chunk.terrain_populated
        {
            c.chunk.terrain_populated = true;
            c.modified = true;
        }
    }

    /// Vanilla `Chunk.populateChunk`, run when `(x, z)` was loaded: populates this chunk
    /// and its west/north neighbours once the chunks they need are loaded.
    fn populate_around(&mut self, x: i32, z: i32) {
        let e = |w: &Self, dx: i32, dz: i32| w.loaded(x + dx, z + dz);
        if e(self, 1, 0) && e(self, 0, 1) && e(self, 1, 1) {
            self.populate(x, z);
        }
        if e(self, -1, 0) && e(self, 0, 1) && e(self, -1, 1) {
            self.populate(x - 1, z);
        }
        if e(self, 0, -1) && e(self, 1, 0) && e(self, 1, -1) {
            self.populate(x, z - 1);
        }
        if e(self, -1, -1) && e(self, 0, -1) && e(self, -1, 0) {
            self.populate(x - 1, z - 1);
        }
    }

    /// Vanilla `Chunk.func_150804_b` for an active chunk: marks it ticked and populates
    /// its light once all eight neighbours are loaded (`func_150809_p`).
    ///
    /// TODO(M5): recompute sky light instead of only setting the flag.
    pub fn tick_chunk(&mut self, cx: i32, cz: i32) {
        self.chunk(cx, cz);
        let neighbours_loaded = (-1..=1).all(|dx| (-1..=1).all(|dz| self.loaded(cx + dx, cz + dz)));
        let c = self.chunks.get_mut(&(cx, cz)).expect("loaded above");
        c.ticked = true;
        if c.from_disk
            && c.chunk.terrain_populated
            && !c.chunk.light_populated
            && (neighbours_loaded || !self.has_sky)
        {
            c.chunk.light_populated = true;
            c.modified = true;
        }
    }

    /// Whether vanilla would send this chunk to players (`Chunk.isPopulated`).
    ///
    /// Whether vanilla would send this chunk (`Chunk.isPopulated`: ticked, terrain and
    /// light populated).
    ///
    /// Chunks missing from disk are never sent: vanilla generates them, which needs M6.
    pub fn is_sendable(&mut self, cx: i32, cz: i32) -> bool {
        self.chunk(cx, cz);
        let c = &self.chunks[&(cx, cz)];
        c.from_disk && c.ticked && c.chunk.terrain_populated && c.chunk.light_populated
    }

    /// Mutable access to a chunk; marks it modified.
    pub fn chunk_mut(&mut self, cx: i32, cz: i32) -> &mut Chunk {
        self.chunk(cx, cz);
        let entry = self.chunks.get_mut(&(cx, cz)).expect("just loaded");
        entry.modified = true;
        &mut entry.chunk
    }

    /// The block state at a world position (air outside 0..256).
    pub fn block(&mut self, x: i32, y: i32, z: i32) -> u16 {
        if !(0..256).contains(&y) {
            return 0;
        }
        self.chunk(x >> 4, z >> 4)
            .block((x & 15) as usize, y as usize, (z & 15) as usize)
    }

    /// The index of the tile entity at `pos` in its (loaded) chunk's list.
    fn tile_entity_index(&self, pos: (i32, i32, i32)) -> Option<usize> {
        let c = &self.chunks.get(&(pos.0 >> 4, pos.2 >> 4))?.chunk;
        c.tile_entities.iter().position(|t| {
            matches!(t, Tag::Compound(c)
                if (c.get_i32("x"), c.get_i32("y"), c.get_i32("z")) == pos)
        })
    }

    /// The tile entity NBT at `pos`, if its chunk is loaded (`World.getTileEntity`).
    pub fn tile_entity(&self, pos: (i32, i32, i32)) -> Option<&Compound> {
        let index = self.tile_entity_index(pos)?;
        let c = &self.chunks.get(&(pos.0 >> 4, pos.2 >> 4))?.chunk;
        match c.tile_entities.get(index)? {
            Tag::Compound(c) => Some(c),
            _ => None,
        }
    }

    /// Mutable tile entity NBT at `pos` (marks the chunk modified).
    pub fn tile_entity_mut(&mut self, pos: (i32, i32, i32)) -> Option<&mut Compound> {
        let index = self.tile_entity_index(pos)?;
        match self
            .chunk_mut(pos.0 >> 4, pos.2 >> 4)
            .tile_entities
            .get_mut(index)?
        {
            Tag::Compound(c) => Some(c),
            _ => None,
        }
    }

    /// Removes the tile entity at `pos` (`World.removeTileEntity`).
    pub fn remove_tile_entity(&mut self, pos: (i32, i32, i32)) {
        self.chunk(pos.0 >> 4, pos.2 >> 4);
        if let Some(index) = self.tile_entity_index(pos) {
            self.chunk_mut(pos.0 >> 4, pos.2 >> 4)
                .tile_entities
                .remove(index);
        }
    }

    /// Keeps tile entities in step with a block change (`Chunk.setBlockState`): the old
    /// block's tile entity goes away when the block changes, and a new chest gets an
    /// empty one.
    ///
    /// TODO(M4): create the tile entities of the other blocks (furnaces, signs, ...).
    fn update_tile_entity(&mut self, pos: (i32, i32, i32), old: u16, new: u16) {
        if old >> 4 != new >> 4 && has_tile_entity(old >> 4) {
            self.remove_tile_entity(pos);
        }
        if matches!(new >> 4, 54 | 146) && self.tile_entity_index(pos).is_none() {
            // TileEntityChest.writeToNBT of a new chest.
            let mut c = Compound::new();
            c.insert("id", Tag::String("Chest".into()));
            c.insert("x", Tag::Int(pos.0));
            c.insert("y", Tag::Int(pos.1));
            c.insert("z", Tag::Int(pos.2));
            c.insert("Lock", Tag::String(String::new()));
            c.insert("Items", Tag::List(List::new()));
            let _ = self
                .chunk_mut(pos.0 >> 4, pos.2 >> 4)
                .tile_entities
                .push(Tag::Compound(c));
        }
    }

    /// Whether the chunk is loaded (vanilla `isBlockLoaded`), without loading it.
    pub fn is_chunk_loaded(&self, cx: i32, cz: i32) -> bool {
        self.chunks.contains_key(&(cx, cz))
    }

    /// Number of loaded chunks.
    pub fn loaded_chunks(&self) -> usize {
        self.chunks.len()
    }

    /// Writes modified chunks to their region files.
    pub fn save_chunks(&mut self, world_time: i64) {
        let now = std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .map_or(0, |d| d.as_secs() as u32);
        let dirty: Vec<(i32, i32)> = self
            .chunks
            .iter()
            .filter(|(_, c)| c.modified)
            .map(|(k, _)| *k)
            .collect();
        for (cx, cz) in dirty {
            let root = self.chunks[&(cx, cz)].chunk.to_nbt(world_time);
            if let Some(region) = self.region(cx, cz)
                && let Err(e) = region.write_chunk(cx & 31, cz & 31, &root, now)
            {
                error!("Failed to save chunk ({cx}, {cz}): {e}");
            }
            if let Some(c) = self.chunks.get_mut(&(cx, cz)) {
                c.modified = false;
            }
        }
        for region in self.regions.values_mut() {
            let _ = region.flush();
        }
    }
}

/// The level: shared `level.dat` plus its dimensions.
#[derive(Debug)]
pub struct Level {
    /// World directory (`level-name`).
    pub dir: PathBuf,
    /// `level.dat` contents.
    pub data: LevelData,
    /// The overworld.
    pub overworld: World,
}

impl Level {
    /// Loads an existing world directory. Returns `None` if it has no readable
    /// `level.dat`.
    pub fn load(dir: &Path) -> Option<Self> {
        let data = LevelData::load(dir).ok().flatten()?;
        Some(Self {
            dir: dir.to_path_buf(),
            data,
            overworld: World::new(0, dir.to_path_buf()),
        })
    }

    /// Loads the spawn area like vanilla's "Preparing start region for level 0": every
    /// chunk within 192 blocks of spawn (25×25 chunks), logging progress each second.
    pub fn prepare_spawn_region(&mut self) {
        info!("Preparing start region for level 0");
        let (sx, sz) = (self.data.spawn_x(), self.data.spawn_z());
        let mut last_report = std::time::Instant::now();
        let mut done = 0;
        for dx in (-192..=192).step_by(16) {
            for dz in (-192..=192).step_by(16) {
                if last_report.elapsed().as_millis() > 1000 {
                    info!("Preparing spawn area: {}%", done * 100 / 625);
                    last_report = std::time::Instant::now();
                }
                self.overworld.chunk((sx + dx) >> 4, (sz + dz) >> 4);
                done += 1;
            }
        }
    }

    /// Saves chunks and `level.dat` without log lines (autosave, `save-all`).
    pub fn save_quietly(&mut self) {
        let time = self.data.time();
        self.overworld.save_chunks(time);
        if let Err(e) = self.data.save(&self.dir) {
            error!("Failed to save level.dat: {e}");
        }
    }

    /// Saves chunks and `level.dat` like vanilla's `saveAllWorlds`, logging each
    /// dimension (vanilla always has three, even with `allow-nether=false`).
    pub fn save_all(&mut self) {
        let name = self.data.level_name().to_owned();
        let time = self.data.time();
        info!("Saving chunks for level '{name}'/Overworld");
        self.overworld.save_chunks(time);
        if let Err(e) = self.data.save(&self.dir) {
            error!("Failed to save level.dat: {e}");
        }
        info!("Saving chunks for level '{name}'/Nether");
        info!("Saving chunks for level '{name}'/The End");
    }
}
