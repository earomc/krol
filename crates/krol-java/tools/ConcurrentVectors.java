// Generates crates/krol-java/tests/concurrent_vectors.rs from a Java 8 JVM. Java 8 matters:
// later JDKs changed ConcurrentHashMap internals (table sizing), and vanilla 1.8.8 runs
// on Java 8. Run from the repository root:
//
//     javac --release 8 -d target/java-vectors crates/krol-java/tools/ConcurrentVectors.java
//     "<java 8>/bin/java" -cp target/java-vectors ConcurrentVectors > crates/krol-java/tests/concurrent_vectors.rs
//
// Each case drives a ConcurrentHashMap-backed Set<Long> (vanilla's
// ChunkProviderServer.droppedChunksSet) with operations drawn from java.util.Random; the
// Rust test draws the same operations with JavaRandom and compares the iteration order
// at each snapshot by length, first element and an order-sensitive hash.

import java.util.Collections;
import java.util.Iterator;
import java.util.Random;
import java.util.Set;
import java.util.concurrent.ConcurrentHashMap;

public class ConcurrentVectors {
    static StringBuilder out = new StringBuilder();

    static long key(int x, int z) {
        return (long) x & 4294967295L | ((long) z & 4294967295L) << 32;
    }

    static void snapshot(Set<Long> set) {
        long h = 0xcbf29ce484222325L;
        for (Long k : set) {
            h = (h ^ k) * 0x100000001b3L;
        }
        Iterator<Long> it = set.iterator();
        String first = it.hasNext() ? "Some(" + it.next() + "_i64)" : "None";
        out.append("        (").append(set.size()).append(", ").append(first).append(", ")
           .append(h).append("_i64),\n");
    }

    static void pollFirst(Set<Long> set) {
        Iterator<Long> it = set.iterator();
        if (it.hasNext()) {
            set.remove(it.next());
        }
    }

    // Random operations around (cx, cz): 6/10 add, 2/10 remove, 2/10 remove the first.
    static void randomCase(String name, long seed, int count, int cx, int cz, int range) {
        out.append("    // ").append(name).append("\n");
        out.append("    check_random(").append(seed).append("_i64, ").append(count).append(", ")
           .append(cx).append(", ").append(cz).append(", ").append(range).append(", &[\n");
        Set<Long> set = Collections.newSetFromMap(new ConcurrentHashMap<Long, Boolean>());
        Random r = new Random(seed);
        for (int i = 0; i < count; i++) {
            int kind = r.nextInt(10);
            if (kind < 8) {
                int x = cx + r.nextInt(2 * range + 1) - range;
                int z = cz + r.nextInt(2 * range + 1) - range;
                if (kind < 6) {
                    set.add(key(x, z));
                } else {
                    set.remove(key(x, z));
                }
            } else {
                pollFirst(set);
            }
            if (i % 50 == 49) {
                snapshot(set);
            }
        }
        out.append("    ]);\n");
    }

    // A player at (cx, cz) with view radius r logging out: every chunk of the square is
    // dropped (x outer, z inner), then unloaded 100 per tick.
    static void squareCase(int cx, int cz, int r) {
        out.append("    check_square(").append(cx).append(", ").append(cz).append(", ").append(r)
           .append(", &[\n");
        Set<Long> set = Collections.newSetFromMap(new ConcurrentHashMap<Long, Boolean>());
        for (int x = cx - r; x <= cx + r; x++) {
            for (int z = cz - r; z <= cz + r; z++) {
                set.add(key(x, z));
            }
        }
        snapshot(set);
        while (!set.isEmpty()) {
            for (int i = 0; i < 100; i++) {
                pollFirst(set);
            }
            snapshot(set);
        }
        out.append("    ]);\n");
    }

    public static void main(String[] args) {
        out.append("// @generated by crates/krol-java/tools/ConcurrentVectors.java on Java ")
           .append(System.getProperty("java.version")).append(". Do not edit.\n\n");
        out.append("mod concurrent_common;\nuse concurrent_common::{check_random, check_square};\n\n");
        out.append("#[test]\nfn dropped_chunk_squares_match_jvm() {\n");
        int[][] squares = {
            {-30, -28, 10}, {0, 0, 10}, {-30, -28, 3}, {5, -7, 6}, {100, 200, 10},
            {-1000, 3000, 8}, {-1, -1, 15}, {31, -32, 12}
        };
        for (int[] s : squares) {
            squareCase(s[0], s[1], s[2]);
        }
        out.append("}\n\n#[test]\nfn random_dropped_chunks_match_jvm() {\n");
        randomCase("small area, many collisions", 1L, 3000, -30, -28, 12);
        randomCase("mixed signs", 2L, 3000, 0, 0, 20);
        randomCase("far away", 3L, 2000, 12345, -54321, 15);
        randomCase("tiny area, deep trees", 4L, 4000, -3, 2, 6);
        randomCase("large area", 5L, 5000, -30, -28, 40);
        out.append("}\n");
        System.out.print(out);
    }
}
