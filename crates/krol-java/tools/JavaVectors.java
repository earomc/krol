// Generates crates/krol-java/tests/java_vectors.rs from a real JVM.
// Run from the repository root:
//
//     java crates/krol-java/tools/JavaVectors.java > crates/krol-java/tests/java_vectors.rs
//
// The algorithms exercised here (java.util.Random, StrictMath.log, String.hashCode,
// DataOutputStream.writeUTF) are unchanged between Java 8 and current JDKs.

import java.io.ByteArrayInputStream;
import java.io.ByteArrayOutputStream;
import java.io.DataOutputStream;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.Enumeration;
import java.util.Hashtable;
import java.util.List;
import java.util.Map;
import java.util.Properties;
import java.util.Random;
import java.util.TreeMap;

public class JavaVectors {
    static final long[] SEEDS = {0L, 1L, -1L, 42L, 123456789L, Long.MIN_VALUE, Long.MAX_VALUE};
    static final int[] BOUNDS = {1, 2, 3, 10, 16, 100, 1000, 1 << 30, Integer.MAX_VALUE};
    static final String[] STRINGS = {
        "", "a", "hello", "minecraft:stone", "Notch", "äöü ß", "\u0000nul", "日本語", "emoji 😀",
        "The quick brown fox jumps over the lazy dog"
    };
    static final double[] LOG_INPUTS = {
        1.0, 2.0, 0.5, 1e-300, 4.9e-324, 1e300, 0.1, 0.9999999, 1.0000001, 3.141592653589793,
        0.25, 0.75, 0.123456789, 0.987654321, 1e-10, 2.2250738585072014e-308
    };

    public static void main(String[] args) throws Exception {
        StringBuilder out = new StringBuilder();
        out.append("// @generated by crates/krol-java/tools/JavaVectors.java on Java ")
           .append(System.getProperty("java.version")).append(". Do not edit.\n\n");
        out.append("#![allow(clippy::bool_assert_comparison)]\n\n");
        out.append("use krol_java::{JavaHashtable, JavaRandom, java_string_hash, strict_log, modified_utf8};\n\n");

        // --- Random ---------------------------------------------------------------
        out.append("#[test]\nfn random_matches_jvm() {\n");
        for (long seed : SEEDS) {
            Random r = new Random(seed);
            out.append("    let mut r = JavaRandom::new(").append(seed).append("_i64);\n");
            for (int i = 0; i < 4; i++)
                out.append("    assert_eq!(r.next_int(), ").append(r.nextInt()).append("_i32);\n");
            for (int bound : BOUNDS)
                out.append("    assert_eq!(r.next_int_bounded(").append(bound).append("), ")
                   .append(r.nextInt(bound)).append(");\n");
            for (int i = 0; i < 3; i++)
                out.append("    assert_eq!(r.next_long(), ").append(r.nextLong()).append("_i64);\n");
            for (int i = 0; i < 3; i++)
                out.append("    assert_eq!(r.next_boolean(), ").append(r.nextBoolean()).append(");\n");
            for (int i = 0; i < 3; i++)
                out.append("    assert_eq!(r.next_float().to_bits(), 0x")
                   .append(Integer.toHexString(Float.floatToRawIntBits(r.nextFloat()))).append("_u32);\n");
            for (int i = 0; i < 3; i++)
                out.append("    assert_eq!(r.next_double().to_bits(), 0x")
                   .append(Long.toHexString(Double.doubleToRawLongBits(r.nextDouble()))).append("_u64);\n");
            for (int i = 0; i < 5; i++)
                out.append("    assert_eq!(r.next_gaussian().to_bits(), 0x")
                   .append(Long.toHexString(Double.doubleToRawLongBits(r.nextGaussian()))).append("_u64);\n");
            // Interleave: gaussian cache must survive setSeed reset semantics.
            r.setSeed(seed ^ 0x1234);
            out.append("    r.set_seed(").append(seed ^ 0x1234).append("_i64);\n");
            out.append("    assert_eq!(r.next_gaussian().to_bits(), 0x")
               .append(Long.toHexString(Double.doubleToRawLongBits(r.nextGaussian()))).append("_u64);\n");
            out.append("    assert_eq!(r.next_int(), ").append(r.nextInt()).append("_i32);\n");
        }
        out.append("}\n\n");

        // --- StrictMath.log -------------------------------------------------------
        out.append("#[test]\nfn strict_log_matches_jvm() {\n");
        for (double d : LOG_INPUTS) {
            out.append("    assert_eq!(strict_log(f64::from_bits(0x")
               .append(Long.toHexString(Double.doubleToRawLongBits(d))).append("_u64)).to_bits(), 0x")
               .append(Long.toHexString(Double.doubleToRawLongBits(StrictMath.log(d)))).append("_u64);\n");
        }
        // A deterministic sweep over (0, 1), the range used by nextGaussian.
        Random sweep = new Random(7);
        long acc = 0;
        for (int i = 0; i < 100_000; i++) {
            acc = acc * 31 + Double.doubleToRawLongBits(StrictMath.log(sweep.nextDouble()));
        }
        out.append("    let mut sweep = JavaRandom::new(7);\n");
        out.append("    let mut acc: i64 = 0;\n");
        out.append("    for _ in 0..100_000 {\n");
        out.append("        acc = acc.wrapping_mul(31).wrapping_add(strict_log(sweep.next_double()).to_bits() as i64);\n");
        out.append("    }\n");
        out.append("    assert_eq!(acc, ").append(acc).append("_i64);\n");
        out.append("}\n\n");

        // --- String.hashCode and writeUTF ----------------------------------------
        out.append("#[test]\nfn string_hash_and_modified_utf8_match_jvm() {\n");
        for (String s : STRINGS) {
            String lit = rustLiteral(s);
            out.append("    assert_eq!(java_string_hash(").append(lit).append("), ")
               .append(s.hashCode()).append("_i32);\n");
            ByteArrayOutputStream bos = new ByteArrayOutputStream();
            new DataOutputStream(bos).writeUTF(s);
            byte[] all = bos.toByteArray();
            StringBuilder bytes = new StringBuilder();
            for (int i = 2; i < all.length; i++) { // skip u16 length prefix
                if (i > 2) bytes.append(", ");
                bytes.append("0x").append(String.format("%02x", all[i] & 0xff));
            }
            out.append("    assert_eq!(modified_utf8::encode(").append(lit).append("), [")
               .append(bytes).append("]);\n");
            out.append("    assert_eq!(modified_utf8::decode(&[").append(bytes).append("]).unwrap(), ")
               .append(lit).append(");\n");
        }
        out.append("}\n\n");

        // --- Hashtable enumeration order -----------------------------------------
        out.append("#[test]\nfn hashtable_order_matches_jvm() {\n");
        for (int trial = 0; trial < 4; trial++) {
            Random kr = new Random(trial);
            List<String> keys = new ArrayList<>();
            int n = 5 + trial * 40;
            for (int i = 0; i < n; i++) keys.add("key-" + Integer.toHexString(kr.nextInt()) + "-" + i);
            Hashtable<String, Integer> ht = new Hashtable<>();
            out.append("    let mut t = JavaHashtable::new();\n");
            for (int i = 0; i < keys.size(); i++) {
                ht.put(keys.get(i), i);
                out.append("    t.insert(\"").append(keys.get(i)).append("\".to_string(), ").append(i).append(");\n");
                if (i % 7 == 3) {
                    String victim = keys.get(i / 2);
                    ht.remove(victim);
                    out.append("    t.remove(\"").append(victim).append("\");\n");
                }
            }
            StringBuilder order = new StringBuilder();
            for (Enumeration<String> e = ht.keys(); e.hasMoreElements();) {
                order.append("\"").append(e.nextElement()).append("\", ");
            }
            out.append("    let keys: Vec<&str> = t.iter().map(|(k, _)| k.as_str()).collect();\n");
            out.append("    assert_eq!(keys, [").append(order).append("]);\n");
        }
        out.append("}\n\n");

        // --- HashMap iteration order -----------------------------------------------
        out.append("#[test]\nfn hashmap_order_matches_jvm() {\n");
        for (int trial = 0; trial < 4; trial++) {
            Random kr = new Random(100 + trial);
            List<String> keys = new ArrayList<>();
            int n = 3 + trial * 60;
            for (int i = 0; i < n; i++) {
                long hi = kr.nextLong(), lo = kr.nextLong();
                keys.add(new java.util.UUID(hi, lo).toString());
            }
            java.util.HashMap<String, Integer> hm = new java.util.HashMap<>();
            out.append("    let mut m = krol_java::JavaHashMap::new();\n");
            for (int i = 0; i < keys.size(); i++) {
                hm.put(keys.get(i), i);
                out.append("    m.insert(\"").append(keys.get(i)).append("\".to_string(), ").append(i).append(");\n");
                if (i % 5 == 2) {
                    String victim = keys.get(i / 3);
                    hm.remove(victim);
                    out.append("    m.remove(\"").append(victim).append("\");\n");
                }
            }
            StringBuilder order = new StringBuilder();
            for (String k : hm.keySet()) order.append("\"").append(k).append("\", ");
            out.append("    let keys: Vec<&str> = m.iter().map(|(k, _)| k.as_str()).collect();\n");
            out.append("    assert_eq!(keys, [").append(order).append("] as [&str; ").append(hm.size()).append("]);\n");
        }
        out.append("}\n\n");

        // --- Properties.load / store ----------------------------------------------
        String[] propInputs = {
            "  a=1\r\nb : 2\n! bang comment\n#hash\\\nc 3\nd\\=e=4\nf=line\\\r\n   cont\ng\\u0041=\\u00e9\\t\nh\nkey with\\ space = v \n\\#notcomment=5\n",
            "x=1\\\\\ny=2\\\\\\\n  z\n   \n\t\f\nlast=no newline\\",
            "a:=b\nc==d\ne =  = f\n:emptykey\n=alsoempty\n#c\\\nnot=continued\n",
            "motd=\u00a7aGreen \u00c3\u00a9\r\rcr=only\r\n\r\nend\\\n",
        };
        out.append("#[test]\nfn properties_load_matches_jvm() {\n");
        out.append("    use krol_java::properties::JavaProperties;\n");
        for (String in : propInputs) {
            byte[] bytes = in.getBytes(StandardCharsets.ISO_8859_1);
            Properties p = new Properties();
            p.load(new ByteArrayInputStream(bytes));
            TreeMap<String, String> sorted = new TreeMap<>();
            for (String k : p.stringPropertyNames()) sorted.put(k, p.getProperty(k));
            out.append("    let p = JavaProperties::load(").append(bytesLiteral(bytes)).append(").unwrap();\n");
            out.append("    let mut got: Vec<(String, String)> = p.iter().map(|(k, v)| (k.to_string(), v.to_string())).collect();\n");
            out.append("    got.sort();\n");
            out.append("    let expected: Vec<(String, String)> = vec![");
            for (Map.Entry<String, String> e : sorted.entrySet())
                out.append("(").append(rustLiteral(e.getKey())).append(".to_string(), ")
                   .append(rustLiteral(e.getValue())).append(".to_string()), ");
            out.append("];\n    assert_eq!(got, expected);\n");
        }
        out.append("}\n\n");
        out.append("#[test]\nfn properties_store_escaping_matches_jvm() {\n");
        out.append("    use krol_java::properties::JavaProperties;\n");
        String[][] entries = {
            {" k=:#!", " v=:#! \t\u00e9\u263a\\"}, {"plain", "a b  c"}, {"ctl\u0001", "\u007f\u0000~"}
        };
        for (String[] kv : entries) {
            Properties p = new Properties();
            p.setProperty(kv[0], kv[1]);
            ByteArrayOutputStream bos = new ByteArrayOutputStream();
            p.store(bos, "c");
            String[] lines = bos.toString("ISO-8859-1").split(System.lineSeparator());
            out.append("    let mut p = JavaProperties::new();\n");
            out.append("    p.set(").append(rustLiteral(kv[0])).append(", ").append(rustLiteral(kv[1])).append(");\n");
            out.append("    let out = String::from_utf8(p.store(\"c\", \"d\", \"\\n\")).unwrap();\n");
            out.append("    assert_eq!(out.lines().nth(2).unwrap(), ").append(rustLiteral(lines[2])).append(");\n");
        }
        out.append("}\n\n");

        // --- Double.toString / Float.toString --------------------------------------
        // Note: JDK 19+ prints the shortest round-trip digits (as krol does); JDK 8
        // occasionally differs. Generate on a modern JDK.
        out.append("#[test]\nfn double_to_string_matches_jvm() {\n");
        Random dr = new Random(9);
        for (int i = 0; i < 300; i++) {
            double d = (dr.nextDouble() - 0.5) * Math.pow(10, dr.nextInt(24) - 10);
            float f = (float) d;
            out.append("    assert_eq!(krol_java::fmt::java_double(f64::from_bits(0x")
               .append(Long.toHexString(Double.doubleToRawLongBits(d))).append("_u64)), \"")
               .append(Double.toString(d)).append("\");\n");
            out.append("    assert_eq!(krol_java::fmt::java_float(f32::from_bits(0x")
               .append(Integer.toHexString(Float.floatToRawIntBits(f))).append("_u32)), \"")
               .append(Float.toString(f)).append("\");\n");
        }
        out.append("}\n\n");

        // --- MathHelper sin table checksum ---------------------------------------
        // Vanilla fills its table with (float) Math.sin(i * PI * 2 / 65536).
        long h = 0xcbf29ce484222325L;
        for (int i = 0; i < 65536; i++) {
            int bits = Float.floatToRawIntBits((float) Math.sin((double) i * Math.PI * 2.0D / 65536.0D));
            h ^= bits & 0xffffffffL;
            h *= 0x100000001b3L;
        }
        out.append("#[test]\nfn sin_table_matches_jvm() {\n");
        out.append("    assert_eq!(krol_java::math::sin_table_fnv1a(), 0x")
           .append(Long.toHexString(h)).append("_u64);\n");
        out.append("}\n");

        System.out.print(out);
    }

    static String bytesLiteral(byte[] bytes) {
        StringBuilder b = new StringBuilder("b\"");
        for (byte x : bytes) {
            int v = x & 0xff;
            if (v == '"' || v == '\\') b.append('\\').append((char) v);
            else if (v < 0x20 || v > 0x7e) b.append(String.format("\\x%02x", v));
            else b.append((char) v);
        }
        return b.append('"').toString();
    }

    static String rustLiteral(String s) {
        StringBuilder b = new StringBuilder("\"");
        s.codePoints().forEach(cp -> {
            if (cp == '"' || cp == '\\') b.append('\\').appendCodePoint(cp);
            else if (cp < 0x20 || cp > 0x7e) b.append(String.format("\\u{%x}", cp));
            else b.appendCodePoint(cp);
        });
        return b.append('"').toString();
    }
}
